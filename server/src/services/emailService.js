// ─── Public API ───────────────────────────────────────────────────────────────

/**
 * sendEmail — dispatch an email via the configured provider.
 *
 * EMAIL_PROVIDER: 'gmail' (dev) | 'sendgrid' (prod)
 */
async function sendEmail({ to, subject, html, text }) {
  const provider = process.env.EMAIL_PROVIDER || 'gmail';

  try {
    switch (provider) {
      case 'sendgrid': return await sendViaSendGrid(to, subject, html, text);
      case 'gmail':
      default:         return await sendViaGmail(to, subject, html, text);
    }
  } catch (err) {
    logger.error(`[emailService] Failed to send to ${to}: ${err.message}`);
    throw err;
  }
}

/**
 * sendHearingAlertEmail — convenience wrapper for the standard hearing alert template.
 */
async function sendHearingAlertEmail({ to, caseTitle, hearingDate, court, cnrNumber, documentUrl }) {
  const dateStr = hearingDate
    ? new Date(hearingDate).toLocaleDateString('en-IN', { month: 'long', day: 'numeric', year: 'numeric' })
    : 'Date TBC';

  const subject = `🏛️ Court Hearing Reminder: ${caseTitle || 'Your Case'} — ${dateStr}`;
  const html    = buildHearingAlertHtml({ caseTitle, hearingDate, court, cnrNumber, documentUrl });
  const text    = `Hearing Reminder\n\nCase: ${caseTitle}\nDate: ${dateStr}\nCourt: ${court || 'As per notice'}\n\nNyayaSetu — nyayasetu.in`;

  return sendEmail({ to, subject, html, text });
}

module.exports = { sendEmail, sendHearingAlertEmail };
