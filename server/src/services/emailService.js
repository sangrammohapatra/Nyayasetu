const logger = require('../../utils/logger');

// ─── Provider: Nodemailer/Gmail ────────────────────────────────────────────────

async function sendViaGmail(to, subject, html, text) {
  const nodemailer = require('nodemailer');

  const transporter = nodemailer.createTransporter({
    host:   process.env.EMAIL_HOST  || 'smtp.gmail.com',
    port:   parseInt(process.env.EMAIL_PORT || '587'),
    secure: process.env.EMAIL_PORT === '465',
    auth: {
      user: process.env.EMAIL_USER,
      pass: process.env.EMAIL_PASS,
    },
  });

  const info = await transporter.sendMail({
    from:    process.env.EMAIL_FROM || '"NyayaSetu" <noreply@nyayasetu.in>',
    to,
    subject,
    html,
    text,
  });

  logger.info(`[email/gmail] Sent to ${to}: ${info.messageId}`);
  return { provider: 'gmail', messageId: info.messageId };
}

// ─── Provider: SendGrid ────────────────────────────────────────────────────────

async function sendViaSendGrid(to, subject, html, text) {
  const sgMail = require('@sendgrid/mail');
  sgMail.setApiKey(process.env.SENDGRID_API_KEY);

  const [response] = await sgMail.send({
    to,
    from:    process.env.EMAIL_FROM || 'noreply@nyayasetu.in',
    subject,
    html,
    text,
  });

  logger.info(`[email/sendgrid] Sent to ${to}, status: ${response.statusCode}`);
  return { provider: 'sendgrid', statusCode: response.statusCode };
}

